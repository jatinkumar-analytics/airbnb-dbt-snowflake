WITH CALCULATED_COLUMN AS (
SELECT
BOOKING_ID,
LISTING_ID,
BOOKING_DATE,
NIGHTS_BOOKED,
BOOKING_AMOUNT,
CLEANING_FEE,
SERVICE_FEE,
{{ multiply('NIGHTS_BOOKED','BOOKING_AMOUNT') }} AS TOTAL_AMOUNT,
{{ add_number('CLEANING_FEE','SERVICE_FEE') }} AS ADDITIONAL_FEE
,BOOKING_STATUS,
CREATED_AT 
from {{ref('bronze_booking')}}
)
SELECT  
BOOKING_ID,
LISTING_ID,
BOOKING_DATE,
NIGHTS_BOOKED,
BOOKING_AMOUNT,
CLEANING_FEE,
SERVICE_FEE,
BOOKING_STATUS,
CREATED_AT ,
{{ add_number('TOTAL_AMOUNT','ADDITIONAL_FEE') }}  AS GRAND_TOTAL
FROM CALCULATED_COLUMN